#!/usr/bin/env pypy3
"""Emit six-register machine semantics and a BLAKE3 G execution proof."""
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT))
from ode.canon import canonical_bytes,parse
from ode.register_proof import theory,composed_g_artifacts,composition_artifacts


def main():
    d=ROOT/'examples'/'proofs'
    t=theory(parse((d/'bits.theory.sexp').read_bytes()))
    g,p=composed_g_artifacts(t)
    composition_goal,composition_proof=composition_artifacts(t)
    for kind,value in (('goal',composition_goal),('proof',composition_proof)):
        (d/f'register-compose.{kind}.sexp').write_bytes(canonical_bytes(value))
    text=['; Six initialized Word32 registers; ADD, XOR, immediate ROR; no memory or flags.',
          '; Abstract machine, not an AArch64 ISA model. Generated by tools/make_register_proof.py.',
          '(theory 3','  (']
    text+=['    '+canonical_bytes(x).decode() for x in t[2]]
    text+=['  )','  ()','  (']
    text+=['    '+canonical_bytes(x).decode() for x in t[4]]
    text+=['  ))']
    (d/'register.theory.sexp').write_text('\n'.join(text)+'\n')
    for kind,value in (('goal',g),('proof',p)):
        (d/f'register-g.{kind}.sexp').write_bytes(canonical_bytes(value))


if __name__=='__main__':
    main()
