#!/usr/bin/env pypy3
"""Export a real rotation/XOR normalization result with a kernel proof."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT))
from tools.proof_files import write_theory
from ode.canon import canonical_bytes, parse
from ode.rotate32_proof import theory
from ode.arx_proof import export_normalizer


def main():
    directory = ROOT / 'examples' / 'proofs'
    t = theory(parse((directory / 'bits.theory.sexp').read_bytes()))
    expression = parse('''(xor32 (ror-16 (xor32 x y))
                           (xor32 (ror-8 (ror-8 x)) (ror-16 y)))''')
    g,p = export_normalizer(t,expression)
    write_theory(directory / 'rotate32.theory.sexp', t, [
        '; Word32 XOR and right rotations by immediate counts 0..31.',
        '; Field 0 is the least significant bit; output field i is input (i+n) mod 32.',
        '; Generated by tools/make_rotate32_proof.py.',
    ])
    for kind,value in (('goal',g),('proof',p)):
        (directory / f'rotate32.{kind}.sexp').write_bytes(canonical_bytes(value))


if __name__ == '__main__':
    main()
