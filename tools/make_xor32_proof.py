#!/usr/bin/env pypy3
"""Emit explicit Word32 semantics and a kernel-checkable XOR rewrite proof."""
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from ode.canon import canonical_bytes, parse
from ode.xor32_proof import theory
from ode.arx_proof import export_normalizer


def main():
    directory = ROOT / 'examples' / 'proofs'
    t = theory(parse((directory / 'bits.theory.sexp').read_bytes()))
    g, p = export_normalizer(t, parse('(xor32 x (xor32 y x))'))
    # The owner reads the theory; the kernel reads its canonical identity.
    # Keep constructor signatures and equations on separate source lines.
    text = ['; Word32: exactly 32 bits; XOR defined field by field.',
            '; Generated by tools/make_xor32_proof.py; all laws are proved.',
            '(theory 3', '  (']
    text += ['    ' + canonical_bytes(d).decode() for d in t[2]]
    text += ['  )', '  ()', '  (']
    text += ['    ' + canonical_bytes(d).decode() for d in t[4]]
    text += ['  ))']
    (directory / 'xor32.theory.sexp').write_text('\n'.join(text) + '\n')
    for kind, value in (('goal',g), ('proof',p)):
        (directory / f'xor32.{kind}.sexp').write_bytes(canonical_bytes(value))


if __name__ == '__main__':
    main()
