#!/usr/bin/env pypy3
"""Emit ripple-carry addition semantics and its commutativity proof."""
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT))
from tools.proof_files import write_theory
from ode.canon import canonical_bytes, parse
from ode.add32_proof import artifacts, identity_artifacts, theory


def main():
    d=ROOT/'examples'/'proofs'
    t=theory(parse((d/'bits.theory.sexp').read_bytes()))
    g,p=artifacts(t)
    zero_goal,zero_proof=identity_artifacts(t)
    for kind,v in (('goal',zero_goal),('proof',zero_proof)):
        (d/f'add32-zero.{kind}.sexp').write_bytes(canonical_bytes(v))
    write_theory(d/'add32.theory.sexp', t, [
        '; Word32 ripple-carry addition; final carry is discarded (modulo 2^32).',
        '; Field 0 is the least significant bit. Generated by tools/make_add32_proof.py.',
    ])
    for kind,v in (('goal',g),('proof',p)):
        (d/f'add32.{kind}.sexp').write_bytes(canonical_bytes(v))


if __name__=='__main__':
    main()
