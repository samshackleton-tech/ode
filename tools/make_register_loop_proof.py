#!/usr/bin/env pypy3
"""Emit unbounded register-program iteration and batching proofs."""
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT))
from tools.proof_files import write_theory
from ode.canon import canonical_bytes,parse
from ode.register_loop_proof import theory,iteration_artifacts,batching_artifacts


def main():
    d=ROOT/'examples'/'proofs'
    t=theory(parse((d/'bits.theory.sexp').read_bytes()))
    write_theory(d/'register-loop.theory.sexp', t, [
        '; Finite register programs, repeated for arbitrary natural counts.',
        '; No native branch or timing semantics. Generated by tools/make_register_loop_proof.py.',
    ])
    for name,maker in (('register-iterate',iteration_artifacts),('register-batch',batching_artifacts)):
        g,p=maker(t)
        for kind,value in (('goal',g),('proof',p)):
            (d/f'{name}.{kind}.sexp').write_bytes(canonical_bytes(value))


if __name__=='__main__':
    main()
