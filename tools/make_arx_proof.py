#!/usr/bin/env pypy3
"""Emit one theory and a composed addition/rotation/XOR normalization proof."""
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parent.parent
sys.path.insert(0,str(ROOT))
from ode.canon import canonical_bytes,parse
from ode.arx_proof import theory,export_normalizer


def main():
    d=ROOT/'examples'/'proofs'
    t=theory(parse((d/'bits.theory.sexp').read_bytes()))
    expression=parse('(xor32 (ror-8 (xor32 (add32 (add32 x y) z) w)) (ror-8 w))')
    g,p=export_normalizer(t,expression)
    text=['; Word32 addition, right rotation, XOR: the shared constructor definitions.',
          '; Field 0 is the least significant bit. Generated by tools/make_arx_proof.py.',
          '(theory 3','  (']
    text+=['    '+canonical_bytes(x).decode() for x in t[2]]
    text+=['  )','  ()','  (']
    text+=['    '+canonical_bytes(x).decode() for x in t[4]]
    text+=['  ))']
    (d/'arx.theory.sexp').write_text('\n'.join(text)+'\n')
    for kind,value in (('goal',g),('proof',p)):
        (d/f'arx.{kind}.sexp').write_bytes(canonical_bytes(value))


if __name__=='__main__':
    main()
