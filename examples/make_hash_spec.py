#!/usr/bin/env pypy3
"""Generate BLAKE3's hash, for one message length, as an Ode specification.

    pypy3 examples/make_hash_spec.py LENGTH > examples/blake3-hash-LENGTH.sexp

The specification takes the message as words (LENGTH padded up to whole
words of a 64-byte block, little-endian) and returns the 8 words of the
32-byte hash. It composes the compression specification -- embedded by
hash under (defs ...) -- exactly as C2SP BLAKE3 sections 2.4-2.6 say:
chunks of 1024 bytes, each a chain of up to 16 compressions starting
from the IV with CHUNK_START on the first and CHUNK_END on the last;
chunk chaining values paired into parent nodes (PARENT flag, counter 0,
block length 64) up the tree; the last compression carries ROOT.

Inputs for every length are the same shape: m0..m(N-1), the padded
message words. Lengths that need no padding word still get a whole last
block of 16 words (zeros where the message ends), as the standard pads.
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from ode.canon import canonical_bytes, hash_of, parse  # noqa: E402

IV = [0x6A09E667, 0xBB67AE85, 0x3C6EF372, 0xA54FF53A,
      0x510E527F, 0x9B05688C, 0x1F83D9AB, 0x5BE0CD19]
CHUNK_START, CHUNK_END, PARENT, ROOT = 1, 2, 4, 8


def main(length):
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "blake3-compress.sexp"), "rb") as f:
        compress = parse(f.read())
    chash = hash_of(compress)
    n_blocks = max(1, (length + 63) // 64)
    n_words = n_blocks * 16
    inputs = [f"m{i}" for i in range(n_words)]
    steps = []
    counter = [0]

    def call(cv, block_words, chunk_counter, block_len, flags, tag):
        outs = [f"{tag}_{i}" for i in range(16)]
        args = " ".join(str(a) for a in cv + block_words +
                        [chunk_counter & 0xFFFFFFFF, chunk_counter >> 32,
                         block_len, flags])
        steps.append(f"(({' '.join(outs)}) (call #{chash.hex()} {args}))")
        return outs

    chunk_cvs = []
    n_chunks = max(1, (length + 1023) // 1024)
    for c in range(n_chunks):
        start = c * 1024
        chunk_len = min(1024, length - start) if length else 0
        blocks = max(1, (chunk_len + 63) // 64)
        cv = [str(v) for v in IV]
        for b in range(blocks):
            boff = start + b * 64
            blen = min(64, length - boff) if length else 0
            words = [f"m{(boff // 4) + i}" for i in range(16)]
            flags = (CHUNK_START if b == 0 else 0) | \
                    (CHUNK_END if b == blocks - 1 else 0)
            is_root = (n_chunks == 1 and b == blocks - 1)
            outs = call(cv, words, c, blen,
                        flags | (ROOT if is_root else 0), f"c{c}b{b}")
            if is_root:
                return finish(inputs, steps, outs[:8])
            cv = outs[:8]
        chunk_cvs.append(cv)

    # Tree: pair chaining values left to right; an odd one carries up.
    level = 0
    while len(chunk_cvs) > 1:
        nxt = []
        for i in range(0, len(chunk_cvs) - 1, 2):
            is_root = (len(chunk_cvs) == 2)
            outs = call([str(v) for v in IV], chunk_cvs[i] + chunk_cvs[i + 1],
                        0, 64, PARENT | (ROOT if is_root else 0),
                        f"p{level}n{i // 2}")
            if is_root:
                return finish(inputs, steps, outs[:8])
            nxt.append(outs[:8])
        if len(chunk_cvs) % 2 == 1:
            nxt.append(chunk_cvs[-1])
        chunk_cvs = nxt
        level += 1
    raise AssertionError("unreachable")


def finish(inputs, steps, outputs):
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "blake3-compress.sexp"), "rb") as f:
        compress = parse(f.read())
    out = ["; BLAKE3 hash of a message of a fixed byte length (C2SP BLAKE3",
           "; sections 2.4-2.6), composed from the compression specification",
           "; embedded under (defs ...) by hash. Generated by",
           "; examples/make_hash_spec.py; this file is the specification of",
           "; record for its length.",
           "(wspec", f"  (name blake3-hash-{LENGTH})",
           f"  (inputs ({' '.join(inputs)}))",
           f"  (defs ((#{hash_of(compress).hex()} "
           f"{canonical_bytes(compress).decode()})))",
           "  (steps ("]
    out += [f"    {s}" for s in steps]
    out.append("    ))")
    out.append(f"  (outputs ({' '.join(outputs)})))")
    sys.stdout.write("\n".join(out) + "\n")
    return 0


if __name__ == "__main__":
    LENGTH = int(sys.argv[1])
    raise SystemExit(main(LENGTH))
