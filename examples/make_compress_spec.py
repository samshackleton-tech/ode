#!/usr/bin/env pypy3
"""Generate examples/blake3-compress.sexp from the BLAKE3 algorithm.

The generator is data, not trust: the file it emits is the specification
of record, checked against the reference implementation and C2SP test
vectors by tests/test_blake3_slice.py. Run from the repo root:

    pypy3 examples/make_compress_spec.py > examples/blake3-compress.sexp
"""
import sys

IV = [0x6A09E667, 0xBB67AE85, 0x3C6EF372, 0xA54FF53A]
PERM = [2, 6, 3, 10, 7, 0, 4, 13, 1, 11, 12, 5, 9, 14, 15, 8]
COLUMNS = [(0, 4, 8, 12), (1, 5, 9, 13), (2, 6, 10, 14), (3, 7, 11, 15)]
DIAGONALS = [(0, 5, 10, 15), (1, 6, 11, 12), (2, 7, 8, 13), (3, 4, 9, 14)]


def main():
    steps = []
    counter = [0]

    def fresh(state):
        return state

    # State names s0..s15 evolve as s<idx>_<n>; track the current name.
    cur = {}
    for i in range(8):
        cur[i] = f"cv{i}"
    for i in range(4):
        steps.append((f"s{8 + i}_0", str(IV[i])))
        cur[8 + i] = f"s{8 + i}_0"
    cur[12] = "counter-lo"
    cur[13] = "counter-hi"
    cur[14] = "block-len"
    cur[15] = "flags"
    for i in range(8, 12):
        cur[i] = f"s{i}_0"

    msg = [f"m{i}" for i in range(16)]

    def g(a, b, c, d, x, y, tag):
        n = counter[0]
        counter[0] += 1
        a1, d1, c1, b1 = f"{tag}a", f"{tag}d", f"{tag}c", f"{tag}b"
        steps.append((a1, f"(add (add {cur[a]} {cur[b]}) {x})"))
        steps.append((d1, f"(rotr (xor {cur[d]} {a1}) 16)"))
        steps.append((c1, f"(add {cur[c]} {d1})"))
        steps.append((b1, f"(rotr (xor {cur[b]} {c1}) 12)"))
        a2, d2, c2, b2 = f"{tag}A", f"{tag}D", f"{tag}C", f"{tag}B"
        steps.append((a2, f"(add (add {a1} {b1}) {y})"))
        steps.append((d2, f"(rotr (xor {d1} {a2}) 8)"))
        steps.append((c2, f"(add {c1} {d2})"))
        steps.append((b2, f"(rotr (xor {b1} {c2}) 7)"))
        cur[a], cur[b], cur[c], cur[d] = a2, b2, c2, d2

    for rnd in range(7):
        for j, (a, b, c, d) in enumerate(COLUMNS):
            g(a, b, c, d, msg[2 * j], msg[2 * j + 1], f"r{rnd}c{j}_")
        for j, (a, b, c, d) in enumerate(DIAGONALS):
            g(a, b, c, d, msg[8 + 2 * j], msg[8 + 2 * j + 1], f"r{rnd}d{j}_")
        msg = [msg[PERM[i]] for i in range(16)]

    outputs = []
    for i in range(8):
        name = f"out{i}"
        steps.append((name, f"(xor {cur[i]} {cur[i + 8]})"))
        outputs.append(name)
    for i in range(8):
        name = f"out{8 + i}"
        steps.append((name, f"(xor {cur[8 + i]} cv{i})"))
        outputs.append(name)

    inputs = ([f"cv{i}" for i in range(8)] + [f"m{i}" for i in range(16)]
              + ["counter-lo", "counter-hi", "block-len", "flags"])
    out = ["; BLAKE3's compression function (C2SP BLAKE3, sections 2.2-2.3):",
           "; 7 rounds over the 16-word state. Generated by",
           "; examples/make_compress_spec.py; the generated file is the",
           "; specification of record for this slice, tested against the",
           "; reference implementation (tests/test_blake3_slice.py).",
           "(wspec", "  (name blake3-compress)",
           f"  (inputs ({' '.join(inputs)}))", "  (steps ("]
    for name, e in steps:
        out.append(f"    ({name} {e})")
    out.append("    ))")
    out.append(f"  (outputs ({' '.join(outputs)})))")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
